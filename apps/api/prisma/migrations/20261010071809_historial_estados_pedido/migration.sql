-- Aditiva (#99): historial de estados del pedido y tres columnas nullable en PEDIDO.
-- - HISTORIAL_ESTADO_PEDIDO: una fila por cambio de estado (alta, confirmar, cada transicion,
--   cancelar y lo que cambia una devolucion). Tabla nueva.
-- - PEDIDO.FECHA_ENTREGA_REAL, MOTIVO_CANCELACION, ID_USUARIO_ALTA: nullable, sin default.
-- FECHA_ENTREGA no se renombra: es la fecha PROMETIDA.
-- Al final completa lo que se sabe de los pedidos existentes, sin inventar (ver mas abajo).

-- AlterTable
ALTER TABLE "PEDIDO" ADD COLUMN     "FECHA_ENTREGA_REAL" TIMESTAMPTZ(3),
ADD COLUMN     "ID_USUARIO_ALTA" BIGINT,
ADD COLUMN     "MOTIVO_CANCELACION" VARCHAR(500);

-- CreateTable
CREATE TABLE "HISTORIAL_ESTADO_PEDIDO" (
    "ID_HISTORIAL_ESTADO_PEDIDO" BIGSERIAL NOT NULL,
    "ID_PEDIDO" BIGINT NOT NULL,
    "ESTADO_ANTERIOR" VARCHAR(30),
    "ESTADO_NUEVO" VARCHAR(30) NOT NULL,
    "FECHA" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ID_USUARIO" BIGINT,
    "ORIGEN" VARCHAR(20) NOT NULL DEFAULT 'PANTALLA',
    "OBSERVACION" VARCHAR(500),

    CONSTRAINT "HISTORIAL_ESTADO_PEDIDO_pkey" PRIMARY KEY ("ID_HISTORIAL_ESTADO_PEDIDO")
);

-- CreateIndex
CREATE INDEX "IX_HISTORIAL_ESTADO_PEDIDO_PEDIDO_FECHA" ON "HISTORIAL_ESTADO_PEDIDO"("ID_PEDIDO", "FECHA");

-- AddForeignKey
ALTER TABLE "PEDIDO" ADD CONSTRAINT "PEDIDO_ID_USUARIO_ALTA_fkey" FOREIGN KEY ("ID_USUARIO_ALTA") REFERENCES "USUARIO"("ID_USUARIO") ON DELETE NO ACTION ON UPDATE NO ACTION;

-- AddForeignKey
ALTER TABLE "HISTORIAL_ESTADO_PEDIDO" ADD CONSTRAINT "HISTORIAL_ESTADO_PEDIDO_ID_PEDIDO_fkey" FOREIGN KEY ("ID_PEDIDO") REFERENCES "PEDIDO"("ID_PEDIDO") ON DELETE NO ACTION ON UPDATE NO ACTION;

-- AddForeignKey
ALTER TABLE "HISTORIAL_ESTADO_PEDIDO" ADD CONSTRAINT "HISTORIAL_ESTADO_PEDIDO_ID_USUARIO_fkey" FOREIGN KEY ("ID_USUARIO") REFERENCES "USUARIO"("ID_USUARIO") ON DELETE NO ACTION ON UPDATE NO ACTION;


-- Datos que ya existen.
-- Fecha real de entrega: es una aproximacion. Un pedido ENTREGADO la toma de FECHA_MODIFICACION.
-- Uno devuelto (DEVUELTO_PARCIAL o DEVUELTO) no puede usar FECHA_MODIFICACION, que es la de la
-- devolucion: toma la de su primera devolucion, que es cuando seguro ya estaba entregado. Se guarda
-- el dia, a las 00:00 de Argentina, como la fecha prometida.
UPDATE "PEDIDO" p
SET "FECHA_ENTREGA_REAL" =
  date_trunc('day', COALESCE(
    CASE WHEN p."ESTADO_PEDIDO" = 'ENTREGADO' THEN p."FECHA_MODIFICACION" END,
    (SELECT MIN(d."FECHA") FROM "DEVOLUCION" d WHERE d."ID_PEDIDO" = p."ID_PEDIDO")
  ) AT TIME ZONE 'America/Argentina/Buenos_Aires') AT TIME ZONE 'America/Argentina/Buenos_Aires'
WHERE p."ESTADO_PEDIDO" IN ('ENTREGADO', 'DEVUELTO_PARCIAL', 'DEVUELTO');

-- Historial: solo lo que se sabe. El alta (sin estado anterior) con FECHA_ALTA y, si se confirmo,
-- la confirmacion con FECHA_CONFIRMACION. Sin usuario. MOTIVO_CANCELACION e ID_USUARIO_ALTA quedan
-- vacios.
INSERT INTO "HISTORIAL_ESTADO_PEDIDO" ("ID_PEDIDO", "ESTADO_ANTERIOR", "ESTADO_NUEVO", "FECHA", "ORIGEN")
SELECT "ID_PEDIDO", NULL, 'PENDIENTE', "FECHA_ALTA", 'PANTALLA' FROM "PEDIDO";

INSERT INTO "HISTORIAL_ESTADO_PEDIDO" ("ID_PEDIDO", "ESTADO_ANTERIOR", "ESTADO_NUEVO", "FECHA", "ORIGEN")
SELECT "ID_PEDIDO", 'PENDIENTE', 'CONFIRMADO', "FECHA_CONFIRMACION", 'PANTALLA'
FROM "PEDIDO"
WHERE "FECHA_CONFIRMACION" IS NOT NULL;
